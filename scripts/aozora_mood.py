# -*- coding: utf-8 -*-
"""一節から、感情の名前と気分の色を決める（2026-07-31・Kosei確定）。

【なぜ一節ごとに決めてよいのか】
主題（恋愛・学校…）は一節から当てられなかった（`aozora_rooms.py` 冒頭に二度の失敗）。
30字の地の文に「何について書かれたか」は書いていないからで、当てにいくと雨の庭が
『いじめ』へ行った。**感情は違う**。「さびしい」と書いてある文はさびしいのであって、
そこに推測が要らない。主題は proxy を探す仕事だが、**感情は書いてある語がそのまま印**。
だからここは一節ごとに決める。書いていない文には、何も付けない。

【七つの名前】
よろこび／かなしみ／つらさ／さびしさ／しずけさ／あたたかさ／こいしさ。
これが部屋の名前になり、人もここへことばを放てる（Kosei確定）。

【色】
新しい色は作らない。宙がすでに持っている**気分7色**（`app._MOOD_SWATCH_HEX`＝
凪・芽・陽・温・恋・憂・沈）へ寄せる。人が選ぶのと同じ7色に落ちるので、紙の色は
人のことばと同じ仕組み（`paperOf()` が seal_color を手染めの紙にする）でそのまま動く。
かなしみ と さびしさ は同じ「憂」の色になる——色は7つしかなく、この二つは同じ温度に居る。
名前が二つあるのは、行き先として別のものだから。

【付けない自由】
どの印も出てこない一節は、部屋も色も持たない＝生成りの紙のまま、どの島の岸にも流れ着く。
「選ばれていない色は空気にしない」（2026-07-28 の恒久ルール）と同じ線で、
**書かれていない気分を、こちらで足さない**。実測で、印が出るのは20万片のうち約5%。
"""

# 感情の名前 → 気分7色のどれか（app._MOOD_SWATCH_HEX の並び：凪芽陽温恋憂沈）
EMOTIONS = ("よろこび", "かなしみ", "つらさ", "さびしさ",
            "しずけさ", "あたたかさ", "こいしさ")

# ── 紙になる色（2026-07-31 実測して直した）──────────────────────
# 気分7色（`app._MOOD_SWATCH_HEX`）をそのまま渡すと、**紙が染まらない**。
# あれは地図に並べるための量子化パレットで、彩度が低い：
#   凪 hsl(169,11%,81%) / 沈 hsl(355,5%,52%) …… `paperOf()` の「彩度12%以上なら
#   手染め」を割って、二色が灰紙のまま落ちる。
# 一方で人が実際に選んでいるのは hsl(199,70%,62%) / hsl(2,73%,56%) の帯。
# なので**色相はパレットのまま**、彩度と明度だけ人の帯へ揃える（新しい色は作らない）。
# 七つで同じ S/L を使うのは、ここで色ごとの見え方を作り込み始めると、
# それは人が選んだ色と competing する別のパレットになってしまうから。
_S, _L = 52, 70
HSL_OF_EMOTION = {
    "しずけさ": "hsl(169, %d%%, %d%%)" % (_S, _L),   # 凪
    "よろこび": "hsl(42, %d%%, %d%%)" % (_S, _L),    # 陽
    "あたたかさ": "hsl(26, %d%%, %d%%)" % (_S, _L),  # 温
    "こいしさ": "hsl(1, %d%%, %d%%)" % (_S, _L),     # 恋
    "かなしみ": "hsl(287, %d%%, %d%%)" % (_S, _L),   # 憂
    "さびしさ": "hsl(287, %d%%, %d%%)" % (_S, _L),   # 憂（かなしみ と同じ温度に居る）
    "つらさ": "hsl(355, %d%%, %d%%)" % (_S, _L),     # 沈
}
HSL_KIZASHI = "hsl(82, %d%%, %d%%)" % (_S, _L)       # 芽（部屋にはしない・色だけ）
MOOD_OF_EMOTION = {
    "よろこび": 2,      # 陽
    "かなしみ": 5,      # 憂
    "つらさ": 6,        # 沈
    "さびしさ": 5,      # 憂（かなしみ と同じ温度に居る）
    "しずけさ": 0,      # 凪
    "あたたかさ": 3,    # 温
    "こいしさ": 4,      # 恋
}
# 部屋にはしないが、色としてだけ残す印（きざし＝芽）。実測189片と小さく、
# 部屋にすると空の島になる——色として置くぶんには、宙の七色が全部そろう。
KIZASHI_MOOD = 1        # 芽

# 近代文学の地の文に実際に出てくる言い方で書く。現代語の感情語彙をそのまま持ってきても
# 明治大正の文には当たらない（「メンタル」も「しんどい」も出てこない）。
MARKS = {
    "よろこび": ("うれし", "嬉し", "たのし", "楽し", "笑っ", "笑い", "笑う", "陽気",
                 "よろこ", "喜ん", "喜び", "晴れやか", "はしゃ", "浮き浮き", "上機嫌"),
    "かなしみ": ("かなし", "悲し", "うら悲", "涙", "泣い", "泣く", "嘆い", "嘆き",
                 "哀れ", "あわれ", "しめっぽ", "胸がふさ"),
    "つらさ": ("苦し", "絶望", "おそろし", "恐ろし", "こわく", "怖ろし", "むごい",
               "にくら", "憎ら", "怒っ", "腹立", "みじめ", "情けなく", "やりきれ",
               "沈んだ気", "耐えがた"),
    "さびしさ": ("さびし", "寂し", "淋し", "心細", "ものう", "やるせ", "わびし",
                 "侘し", "ひとりぼっち", "所在なく", "とりのこされ"),
    "しずけさ": ("しずか", "静か", "しづか", "穏やか", "おだやか", "ひっそり", "しんと",
                 "やすらか", "安らか", "落ちつい", "落ち着い", "澄んで", "凪い",
                 "音もなく", "のどか", "ゆったり"),
    "あたたかさ": ("あたたか", "温か", "やさし", "優し", "なつかし", "懐かし",
                   "ぬくもり", "いとおし", "情けぶか", "なごやか", "ほほえ", "微笑"),
    # 「切な」「せつな」は**語尾まで書く**。この二つだけで「親切な」「大切な」
    # 「たいせつな」を全部拾ってしまい、〈親切な言葉ひとつ掛ける者はない〉が
    # こいしさとして出てきた（2026-07-31 実測）。部分一致の辞書は、短い語ほど危ない。
    "こいしさ": ("恋し", "恋い", "慕っ", "慕わし", "逢いた", "会いたく", "いとしい",
                 # 「ときめ」も同じ罠だった：〈散歩しようときめていた〉＝「と決めて」。
                 "胸がとき", "ときめい", "ときめき", "ときめか",
                 "切ない", "切なく", "切なさ", "せつない",
                 "せつなく", "思いこがれ", "焦がれ"),
}
# 部屋にはしない、色だけの印
KIZASHI_MARKS = ("芽ぐ", "芽が", "若葉", "青葉", "みずみずし", "生き生き", "いきいき",
                 "ふくらん", "咲きはじ", "咲き初", "きざし", "息吹", "はりきっ", "心はず")

# ── 外した語と、その理由（同じ間違いをもう一度しないために）──────────
# 「明るい」「輝い」 … 物の光であって気持ちではない。水晶がキラキラ輝く一節が
#                     よろこびとして出てきた。
# 「暗い」「冷たい」 … 牢屋の描写。「石の牢屋はお城の地の下の、真暗なつめたいところ」。
# 「愛らし」        … 「可愛らしい口」は恋ではない。物の愛らしさは、こいしさではない。
# 「みなぎ」        … 「不満の色がみなぎっている」がきざしになる。
# 「死んで」「運命」 … 物語の地の文に普通に出てくる（部屋の側でも同じ理由で外した）。


def _count(t, marks):
    return sum(t.count(w) for w in marks)


def color_of(emotion, kizashi=False):
    """感情の名前 → 紙になる色。名前が無くて「きざし」だけの時は芽の色。"""
    if emotion:
        return HSL_OF_EMOTION.get(emotion)
    return HSL_KIZASHI if kizashi else None


def emotion_of(text):
    """一節 → (感情の名前, 気分の色の番号, 内訳)。印が出てこなければ (None, None, {})。

    同じ数で並んだら決めない。感情は一つに絞れるものではないので、二つ出たら
    「どちらとも言える」＝何も付けないほうが正しい。"""
    t = str(text or "")
    hits = {e: n for e in EMOTIONS if (n := _count(t, MARKS[e]))}
    kiz = _count(t, KIZASHI_MARKS)
    if not hits:
        # 部屋にはならないが、きざしの色だけは付く
        return (None, KIZASHI_MOOD, {"きざし": kiz}) if kiz else (None, None, {})
    rank = sorted(hits.items(), key=lambda kv: (-kv[1], EMOTIONS.index(kv[0])))
    if len(rank) > 1 and rank[0][1] == rank[1][1]:
        return None, None, dict(rank[:3])
    if kiz > rank[0][1]:
        return None, KIZASHI_MOOD, dict(rank[:2])
    top = rank[0][0]
    return top, MOOD_OF_EMOTION[top], dict(rank[:3])


def summarize(assigned):
    """割り当ての内訳を、人が読める一枚に。数えるためではなく、疑うために出す。"""
    from collections import Counter
    c = Counter(e for e in assigned if e)
    none_n = sum(1 for e in assigned if not e)
    lines = ["  感情の名がついた一節: %d / %d" % (len(assigned) - none_n, len(assigned))]
    for e in EMOTIONS:
        if c.get(e):
            lines.append("    %-6s %7d片" % (e, c[e]))
    lines.append("    %-6s %7d片（名前なし＝いままでどおり）" % ("——", none_n))
    return "\n".join(lines)
