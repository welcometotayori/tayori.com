# 「決め手」の線。本まるごとを数えるので、印がいくつか出るのは当たり前——
# 一位が二位を**はっきり上回った時だけ**部屋を当てる。
MIN_HITS = 8          # 一位の印がこの数に届かない本は、主題が薄い＝当てない
MIN_RATIO = 1.6       # 一位 ÷ 二位。1.6 を割るなら「どちらとも言える」＝当てない


def count_marks(text):
    """本文に、部屋の印がいくつ出るか。重なりは数えない（同じ語の再出は数える）。"""
    t = str(text or "")
    return {room: sum(t.count(w) for w in marks) for room, marks in ROOM_MARKS.items()}


# ── 生の数で決めてはいけない理由（2026-07-31・実測して直した）─────────
# 最初は「印がいちばん多く出た部屋」にしていた。160冊で見た結果、**長い小説がぜんぶ
# 家族へ行った**：海野十三『霊魂第十号の秘密』（探偵物）が家族82、山本禾太郎
# 『抱茗荷の説』（怪奇物）が家族57。母・父・息子は、**どんな小説にも出てくる**。
# 長いほど多く出るのだから、生の数はほとんど「本の長さ」を測っている。
#
# なので、その本の率を**全部の本の平均の率**と比べる。家族の部屋に行くのは
# 「家族の語が出てくる本」ではなく「**ふつうの本より家族の語が濃い本**」になる。
# 平均は与えられた本の集合そのものから作る（外から数字を持ち込まない＝決定的）。
def corpus_rates(counts_and_lens):
    """[(印の数の辞書, 本文の長さ), …] → 部屋ごとの「ふつうの濃さ」。"""
    tot_hits = {r: 0 for r in ROOM_MARKS}
    tot_len = 0
    for hits, n in counts_and_lens:
        tot_len += max(1, n)
        for r, v in hits.items():
            tot_hits[r] += v
    tot_len = max(1, tot_len)
    # 一度も出ない部屋は、平均を極小にすると一冊の当たりで爆発する。下限を置く。
    return {r: max(tot_hits[r] / tot_len, 1e-7) for r in ROOM_MARKS}


def room_of_work(text, rates=None):
    """本まるごと → (部屋名, なぜそう決めたかの内訳)。決め手が無ければ (None, …)。

    rates を渡すと「ふつうの濃さ」との比で決める（推奨）。渡さなければ生の数で決める
    ——下見や単体の確認のための逃げ道で、取り込みでは必ず渡す。"""
    t = str(text or "")
    raw = count_marks(t)
    hits = {r: n for r, n in raw.items() if n}
    if not hits:
        return None, {}
    if rates:
        n = max(1, len(t))
        score = {r: (v / n) / rates[r] for r, v in hits.items()}
    else:
        score = dict(hits)
    rank = sorted(score.items(), key=lambda kv: (-kv[1], kv[0]))
    top = rank[0][0]
    s1 = rank[0][1]
    s2 = rank[1][1] if len(rank) > 1 else 0.0
    why = {r: raw[r] for r, _s in rank[:3]}
    if raw[top] < MIN_HITS:
        return None, why                  # 印そのものが薄い本は、当てない
    if s2 and s1 < s2 * MIN_RATIO:
        return None, why                  # どちらとも言える本は、どこにも置かない
    return top, why


def summarize(assigned):
    """割り当ての内訳を、人が読める一枚に。数えるためではなく、疑うために出す。"""
    c = Counter(r for r in assigned if r)
    none_n = sum(1 for r in assigned if not r)
    lines = ["  部屋が決まった本: %d / %d" % (len(assigned) - none_n, len(assigned))]
    for room, n in c.most_common():
        lines.append("    %-6s %5d冊" % (room, n))
    lines.append("    %-6s %5d冊（部屋なし＝どの島の岸にも流れ着く）" % ("——", none_n))
    return "\n".join(lines)
